"""Streamlit front end for the local Smart Document Assistant.

The application consumes two generated, local artifacts: a FAISS index and a
GGUF-compatible model.  Their locations are configurable with environment
variables so the app does not depend on a Kaggle or user-specific path.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import streamlit as st

PROJECT_ROOT = Path(__file__).resolve().parent
DEFAULT_INDEX_DIR = PROJECT_ROOT / "faiss_index_arxiv"
DEFAULT_MODEL_DIR = PROJECT_ROOT / "models" / "llama-2-7b-chat"
DEFAULT_MODEL_FILE = "llama-2-7b-chat.Q4_K_M.gguf"
DEFAULT_EMBEDDING_MODEL = "sentence-transformers/all-MiniLM-L6-v2"
NOT_FOUND_MESSAGE = "Not mentioned in the documents."


def _path_from_env(name: str, default: Path) -> Path:
    """Return an absolute path from an environment variable or project default."""

    configured = os.getenv(name)
    path = Path(configured).expanduser() if configured else default
    return path if path.is_absolute() else PROJECT_ROOT / path


def _require_file(path: Path, description: str) -> None:
    if not path.is_file():
        raise RuntimeError(
            f"{description} was not found at '{path}'. "
            "Generate/download the local artifact as described in README.md, "
            "or set the corresponding environment variable."
        )


def _positive_int_env(name: str, default: int) -> int:
    """Read a positive integer environment setting with a useful error."""

    raw_value = os.getenv(name, str(default))
    try:
        value = int(raw_value)
    except ValueError as exc:
        raise ValueError(f"{name} must be a positive integer, got {raw_value!r}") from exc
    if value <= 0:
        raise ValueError(f"{name} must be a positive integer, got {value}")
    return value


@st.cache_resource
def load_llm(
    model_dir: str,
    model_file: str,
    model_type: str,
    max_new_tokens: int,
    context_length: int,
) -> Any:
    """Load the configured local CTransformers model exactly once per process."""

    from langchain_community.llms import CTransformers

    model_path = Path(model_dir)
    model_name = Path(model_file)
    if model_name.is_absolute() or model_name.name != model_file:
        raise ValueError("LLM_MODEL_FILE must be a filename inside LLM_MODEL_DIR")
    model_file_path = model_path / model_file
    _require_file(model_file_path, "LLM model file")
    return CTransformers(
        model=str(model_path),
        model_file=model_file,
        model_type=model_type,
        config={
            "temperature": 0.0,
            "max_new_tokens": max_new_tokens,
            "context_length": context_length,
        },
    )


@st.cache_resource
def load_vector_store(index_dir: str, embedding_model: str, embedding_device: str) -> Any:
    """Load a trusted, locally generated FAISS index."""

    from langchain_community.embeddings import HuggingFaceEmbeddings
    from langchain_community.vectorstores import FAISS

    index_path = Path(index_dir)
    _require_file(index_path / "index.faiss", "FAISS index")
    _require_file(index_path / "index.pkl", "FAISS metadata")
    embeddings = HuggingFaceEmbeddings(
        model_name=embedding_model,
        model_kwargs={"device": embedding_device},
    )
    # FAISS.load_local requires this flag for its pickle metadata. Only load
    # indexes generated by this project or another explicitly trusted source.
    return FAISS.load_local(
        str(index_path), embeddings, allow_dangerous_deserialization=True
    )


def build_qa_chain(llm: Any, vector_store: Any) -> Any:
    """Create the retrieval chain with a grounded-answer prompt."""

    from langchain.chains import RetrievalQA
    from langchain_core.prompts import PromptTemplate

    template = """You are a strict document-based assistant.
Answer only using the provided context. If the answer is not present, say
\"Not mentioned in the documents.\"

Context: {context}
Question: {question}

Answer:
"""
    prompt = PromptTemplate(template=template, input_variables=["context", "question"])
    return RetrievalQA.from_chain_type(
        llm=llm,
        chain_type="stuff",
        retriever=vector_store.as_retriever(search_kwargs={"k": 3}),
        return_source_documents=True,
        chain_type_kwargs={"prompt": prompt},
    )


def format_response(answer: str, sources: list[Any]) -> str:
    """Render an answer and stable, de-duplicated source references."""

    answer = answer.strip() or NOT_FOUND_MESSAGE
    if NOT_FOUND_MESSAGE.lower() in answer.lower():
        return answer
    source_names = {
        f"- {(getattr(doc, 'metadata', None) or {}).get('source', 'Unknown source')} "
        f"(Page {(getattr(doc, 'metadata', None) or {}).get('page', 'N/A')})"
        for doc in sources
    }
    source_text = "\n".join(sorted(source_names)) or "- No source metadata available"
    return f"{answer}\n\n**Sources:**\n{source_text}"


def main() -> None:
    st.set_page_config(page_title="Smart Document Assistant", layout="wide")
    st.title("Smart Document Assistant")

    index_dir = _path_from_env("FAISS_INDEX_DIR", DEFAULT_INDEX_DIR)
    model_dir = _path_from_env("LLM_MODEL_DIR", DEFAULT_MODEL_DIR)
    model_file = os.getenv("LLM_MODEL_FILE", DEFAULT_MODEL_FILE)
    embedding_model = os.getenv("EMBEDDING_MODEL", DEFAULT_EMBEDDING_MODEL)
    embedding_device = os.getenv("EMBEDDING_DEVICE", "cpu")
    model_type = os.getenv("LLM_MODEL_TYPE", "llama")

    try:
        vector_store = load_vector_store(
            str(index_dir), embedding_model, embedding_device
        )
        llm = load_llm(
            str(model_dir),
            model_file,
            model_type,
            _positive_int_env("LLM_MAX_NEW_TOKENS", 512),
            _positive_int_env("LLM_CONTEXT_LENGTH", 2048),
        )
        qa_chain = build_qa_chain(llm, vector_store)
    except Exception as exc:
        st.error(f"The assistant is not ready: {exc}")
        st.info(
            "This repository does not include the document PDFs, FAISS index, "
            "or model weights. Follow the setup steps in README.md."
        )
        return

    if "messages" not in st.session_state:
        st.session_state.messages = []
    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            st.markdown(message["content"])

    if prompt := st.chat_input("Ask anything about the documents..."):
        st.session_state.messages.append({"role": "user", "content": prompt})
        with st.chat_message("user"):
            st.markdown(prompt)
        with st.chat_message("assistant"), st.spinner("Generating a grounded answer..."):
            try:
                response = qa_chain.invoke({"query": prompt})
                answer = str(response.get("result", NOT_FOUND_MESSAGE)).strip()
                sources = response.get("source_documents", [])
                full_response = format_response(answer, sources)
            except Exception as exc:
                full_response = f"The assistant could not answer this question: {exc}"
            st.markdown(full_response)
            st.session_state.messages.append(
                {"role": "assistant", "content": full_response}
            )


if __name__ == "__main__":
    main()
